"""Build a curated, static showcase from two fresh mock-runner examples.

This module intentionally has no input path for arbitrary operator artifacts.
It creates the two repository demo runs in a temporary directory, then exports
only normalized API snapshots and a generated synthetic media clip.
"""

from __future__ import annotations

