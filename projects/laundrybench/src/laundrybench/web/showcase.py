from laundrybench.evaluation.metadata import write_experiment_metadata
from laundrybench.web.server import RunStore

SOURCE_REPOSITORY = "https://github.com/chungtseng96/embodied-ai-lab"
CANDIDATE_ID = "exp-901-mock-candidate"
BASELINE_ID = "exp-900-mock-baseline"
_COMMIT = re.compile(r"[0-9a-f]{40}\Z")
_VITE_ASSET = re.compile(r"/assets/[A-Za-z0-9_-]+-[A-Za-z0-9_-]{8,}\.(?:js|css)\Z")
_MAX_WALKTHROUGH_BYTES = 50 * 1024 * 1024

LIMITATIONS = [
    "Both runs are generated by LaundryBench's mock robot and seeded mock success judge.",
    (
        "The curated reviewed labels are synthetic fixtures derived from mock outcomes, not human "
        "annotation."
    ),
    (
        "The checkpoint identities and configuration changes are illustrative metadata; no "
        "training or checkpoint was used."
    ),
    (
        "The small, seeded sample supports UI and workflow demonstration only; it cannot establish "
        "a performance improvement."
    ),
    "An optional walkthrough clip records the software UI only, not robot or camera footage.",
    "Synthetic test-pattern video is generated locally and is not robot or camera footage.",
    "No hardware, physical camera synchronization, or real-world task execution was exercised.",
]


class _ViteIndexParser(HTMLParser):
    """Collect only safe external JS and stylesheet references from Vite index."""

    _ATTRS: ClassVar[dict[str, set[str]]] = {
        "html": {"lang"},
        "head": set(),
        "meta": {"charset", "name", "content"},
        "title": set(),
        "body": set(),
        "div": {"id"},
        "script": {"type", "crossorigin", "src"},
        "link": {"rel", "crossorigin", "href"},
    }

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.references: set[str] = set()
        self.errors: list[str] = []
        self.in_script = False
        self.script_count = 0
        self.style_count = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag not in self._ATTRS:
            self.errors.append(f"unsupported HTML element <{tag}>")
            return
        names = [name for name, _ in attrs]
        attributes = dict(attrs)
        if len(names) != len(attributes) or set(names) - self._ATTRS[tag]:
            self.errors.append(f"unsupported attributes on <{tag}>")
            return
        if tag == "meta":
            if "charset" in attributes:
                charset = attributes["charset"]
                if (
                    set(attributes) != {"charset"}
                    or not isinstance(charset, str)
                    or charset.lower() != "utf-8"
                ):
                    self.errors.append("unsupported charset declaration")
            elif set(attributes) != {"name", "content"} or attributes.get("name") not in {
                "viewport",
                "description",
            }:
                self.errors.append("unsupported meta declaration")
        elif tag == "div" and attributes != {"id": "root"}:
            self.errors.append("only the Vite root element is allowed")
        elif tag == "script":
            src = attributes.get("src")
            if attributes.get("type") != "module" or not src or self.in_script:
                self.errors.append("only external Vite module scripts are allowed")
                return
            if not _VITE_ASSET.fullmatch(src) or not src.endswith(".js"):
                self.errors.append("Vite module script must reference a hashed JS asset")
                return
            self.in_script = True
            self.script_count += 1
            self.references.add(src)
        elif tag == "link":
            href = attributes.get("href")
            if attributes.get("rel") != "stylesheet" or not href:
                self.errors.append("only external stylesheet links are allowed")
                return
            if not _VITE_ASSET.fullmatch(href) or not href.endswith(".css"):
                self.errors.append("stylesheet link must reference a hashed CSS asset")
                return
            self.style_count += 1
            self.references.add(href)

    def handle_endtag(self, tag: str) -> None:
        if tag == "script":
            if not self.in_script:
                self.errors.append("unexpected script closing tag")
            self.in_script = False
        elif tag not in self._ATTRS:
            self.errors.append(f"unsupported HTML closing element </{tag}>")

    def handle_data(self, data: str) -> None:
        if self.in_script and data.strip():
            self.errors.append("inline script content is not allowed")

    def handle_decl(self, decl: str) -> None:
        if decl.lower() != "doctype html":
            self.errors.append("only an HTML5 doctype is allowed")


def _preflight_output(output_dir: Path, *, require_frontend: bool) -> None:
    """Fail closed unless the existing tree is empty or a clean Vite build."""
    absolute = Path(os.path.abspath(output_dir))
    cursor = absolute
    while cursor != cursor.parent:
        if cursor.is_symlink():
            raise ValueError(f"showcase output path contains a symlink: {cursor}")
        cursor = cursor.parent
    if not absolute.exists():
        if require_frontend:
            raise ValueError(
                f"frontend build not found at {absolute}; build with VITE_SHOWCASE=1 first"
            )
        return
    if not absolute.is_dir():
        raise ValueError("showcase output must be a directory")
    entries = list(absolute.iterdir())
    for path in entries:
        if path.is_symlink():
            raise ValueError(f"showcase output contains a symlink: {path}")
    if not entries:
        if require_frontend:
            raise ValueError(
                f"frontend build is empty at {absolute}; build with VITE_SHOWCASE=1 first"
            )
        return
    if {path.name for path in entries} != {"index.html", "assets"}:
        unexpected = sorted(
            path.name for path in entries if path.name not in ("index.html", "assets")
        )
        raise ValueError(
            "showcase output must be a fresh Vite build containing only index.html and assets/; "
            f"unexpected entries: {', '.join(unexpected) or 'missing expected entries'}"
        )

    index_path = absolute / "index.html"
    assets_dir = absolute / "assets"
    if not index_path.is_file() or not assets_dir.is_dir() or assets_dir.is_symlink():
        raise ValueError("showcase output requires a regular index.html and assets/ directory")
    try:
        markup = index_path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        raise ValueError("showcase index.html is missing or unreadable") from error
    parser = _ViteIndexParser()
    try:
        parser.feed(markup)
        parser.close()
    except Exception as error:
        raise ValueError("showcase index.html is not valid safe HTML") from error
    if parser.errors or parser.script_count != 1 or parser.style_count > 1:
        reason = parser.errors[0] if parser.errors else "unexpected Vite entrypoint count"
        raise ValueError(f"showcase index.html is not a safe Vite entrypoint: {reason}")
    if not parser.references or any(not _VITE_ASSET.fullmatch(ref) for ref in parser.references):
        raise ValueError(
            "showcase index.html may reference only hashed /assets/*.js and *.css files"
        )

    referenced_names = {Path(ref).name for ref in parser.references}
    asset_entries = list(assets_dir.iterdir())
    for asset in asset_entries:
        if asset.is_symlink():
            raise ValueError(f"showcase assets contain a symlink: {asset}")
        if not asset.is_file():
            raise ValueError("showcase assets/ may contain only direct regular files")
        if asset.name not in referenced_names:
            raise ValueError(f"showcase assets contain an unreferenced file: {asset.name}")
        if not re.fullmatch(r"[A-Za-z0-9_-]+-[A-Za-z0-9_-]{8,}\.(?:js|css)", asset.name):
            raise ValueError(f"showcase asset name is not a hashed Vite JS/CSS asset: {asset.name}")
    if {asset.name for asset in asset_entries} != referenced_names:
        raise ValueError("showcase index references a missing JS/CSS asset")


def _write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(
        json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8"
    )
    os.replace(temporary, path)


def _run_demo(output_root: Path) -> None:
    """Execute the existing demo runner in a clean, private temporary root."""
    project = Path(__file__).resolve().parents[3]
    script = project / "scripts" / "demo_web.py"
    env = os.environ.copy()
    src = str(project / "src")
    env["PYTHONPATH"] = src + (os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else "")
    subprocess.run(
        [sys.executable, str(script), "--output-dir", str(output_root)],
        cwd=project,
        env=env,
        check=True,
        capture_output=True,
        text=True,
    )


def _curate_context(source_root: Path) -> None:
    candidate = source_root / CANDIDATE_ID
    baseline = source_root / BASELINE_ID
    common = {
        "task": {"id": "laundry-sort-single-item", "version": "1.0"},
        "protocol": {"id": "mock-fixed-placement-v1", "version": "1.0"},
        "dataset": {"id": "synthetic-demo", "revision": "seed-17"},
    }
    contexts = {
        candidate: {
            **common,
            "name": "Illustrative targeted-policy candidate",
            "hypothesis": (
                "A hypothetical checkpoint trained with extra missed-grasp demonstrations might "
                "handle the fixed mock task more reliably. This generated run does not test that "
                "claim."
            ),
            "what_changed": (
                "Illustrative metadata only: a hypothetical targeted-data checkpoint and a higher "
                "mock judge probability setting. No training occurred."
            ),
            "checkpoint": {"identity": "hypothetical-targeted-data-checkpoint-v2"},
            "effective_overrides": {
                "demo_judge_success_probability": 0.8,
                "checkpoint_is_hypothetical": True,
                "training_performed": False,
            },
        },
        baseline: {
            **common,
            "name": "Illustrative mock baseline",
            "hypothesis": (
                "Reference mock run for the same task and protocol. The seeded judge creates "
                "illustrative outcomes; this is not a measured model baseline."
            ),
            "what_changed": "No hypothetical targeted-data adjustment; seeded mock judge fixture.",
            "checkpoint": {"identity": "hypothetical-baseline-checkpoint-v1"},
            "effective_overrides": {
                "demo_judge_success_probability": 0.2,
                "checkpoint_is_hypothetical": True,
                "training_performed": False,
            },
        },
    }
    for run_dir, context in contexts.items():
        write_experiment_metadata(run_dir, context)
        # Keep a review-shaped sidecar for the UI, while stating that these
        # fixture labels are mock-derived and not human review.
        raw_records = [
            json.loads(line)
            for line in (run_dir / "episodes.jsonl").read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]
        labels = {
            "schema_version": 2,
            "revision": len(raw_records),
            "labels": {},
        }
        for index, record in enumerate(raw_records, start=1):
            labels["labels"][record["episode_id"]] = {
                "status": "reviewed",
                "success": record["success"],
                "intervention": record.get("intervention", False),
                "failure_category": record.get("failure_category"),
                "notes": (
                    "Synthetic showcase fixture; copied from seeded MockSuccessJudge output, "
                    "not human-reviewed."
                ),
                "revision": index,
                "updated_at": "2026-11-01T00:00:00+00:00",
            }
        _write_json(run_dir / "labels.json", labels)


def _synthetic_video() -> bytes:
    """Generate short playable footage from ffmpeg's built-in test pattern."""
    if shutil.which("ffmpeg") is None:
        raise RuntimeError("ffmpeg is required to build the synthetic showcase media")
    with tempfile.TemporaryDirectory(prefix="laundrybench-showcase-video-") as temp:
        path = Path(temp) / "synthetic.mp4"
        subprocess.run(
            [
                "ffmpeg",
                "-hide_banner",
                "-loglevel",
                "error",
                "-y",
                "-f",
                "lavfi",
                "-i",
                "testsrc2=size=640x360:rate=12:duration=3",
                "-an",
                "-c:v",
                "libx264",
                "-pix_fmt",
                "yuv420p",
                "-movflags",
                "+faststart",
                str(path),
            ],
            check=True,
            capture_output=True,
        )
        return path.read_bytes()


def _read_walkthrough_video(path: Path | None) -> tuple[bytes | None, str | None]:
    """Read one explicitly curated Playwright walkthrough recording safely."""
    if path is None:
        return None, None
    path = Path(path)
    suffix = path.suffix.lower()
    if suffix not in {".mp4", ".webm"}:
        raise ValueError("walkthrough video must be a local .mp4 or .webm file")
    try:
        initial = path.lstat()
    except OSError as error:
        raise ValueError("walkthrough video is missing or cannot be opened safely") from error
    if stat.S_ISLNK(initial.st_mode):
        raise ValueError("walkthrough video symlinks are not supported")
    if not stat.S_ISREG(initial.st_mode):
        raise ValueError("walkthrough video must be a regular local file")
    if not 0 < initial.st_size <= _MAX_WALKTHROUGH_BYTES:
        raise ValueError("walkthrough video must be non-empty and at most 50 MiB")
    flags = (
        os.O_RDONLY
        | getattr(os, "O_BINARY", 0)
        | getattr(os, "O_NOFOLLOW", 0)
        | getattr(os, "O_NONBLOCK", 0)
    )
    try:
        descriptor = os.open(path, flags)
    except OSError as error:
        raise ValueError("walkthrough video is missing or cannot be opened safely") from error
    with os.fdopen(descriptor, "rb") as handle:
        info = os.fstat(handle.fileno())
        if not stat.S_ISREG(info.st_mode):
            raise ValueError("walkthrough video must be a regular local file")
        if not 0 < info.st_size <= _MAX_WALKTHROUGH_BYTES:
            raise ValueError("walkthrough video must be non-empty and at most 50 MiB")
        data = handle.read(_MAX_WALKTHROUGH_BYTES + 1)
    if len(data) != info.st_size or len(data) > _MAX_WALKTHROUGH_BYTES:
        raise ValueError("walkthrough video changed while it was being read")
    return data, suffix


def export_showcase(
    output_dir: Path,
    *,
    source_commit: str,
    video_factory: Callable[[], bytes] = _synthetic_video,
    require_frontend: bool = False,
    walkthrough_video: Path | None = None,
) -> dict:
    """Build the static allowlisted showcase beneath ``output_dir``.

    Existing output directories must be empty or contain only a fresh, safe
    Vite build. Unknown content is rejected and left untouched. ``video_factory``
    is injectable for unit tests, while the CLI requires ffmpeg.
    """
    if not isinstance(source_commit, str) or not _COMMIT.fullmatch(source_commit):
        raise ValueError("source_commit must be a 40-character lowercase hexadecimal commit")
    walkthrough_bytes, walkthrough_suffix = _read_walkthrough_video(walkthrough_video)
    output_dir = Path(output_dir)
    _preflight_output(output_dir, require_frontend=require_frontend)
    video_bytes = video_factory()
    if not isinstance(video_bytes, bytes) or not video_bytes:
        raise ValueError("synthetic video factory must return non-empty bytes")
    media_hash = hashlib.sha256(video_bytes).hexdigest()
    media_name = f"{media_hash}.mp4"
    walkthrough_hash = (
        hashlib.sha256(walkthrough_bytes).hexdigest() if walkthrough_bytes is not None else None
    )
    walkthrough_name = (
        f"{walkthrough_hash}{walkthrough_suffix}"
        if walkthrough_hash is not None and walkthrough_suffix is not None
        else None
    )
    output_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="laundrybench-showcase-runs-") as temp:
        source_root = Path(temp)
        _run_demo(source_root)
        _curate_context(source_root)
        store = RunStore(source_root)
        # Include candidate first, followed by its matched baseline.
        run_ids = [CANDIDATE_ID, BASELINE_ID]
        details = {run_id: store.detail(run_id) for run_id in run_ids}
        summaries = [
            {
                key: value
                for key, value in details[run_id].items()
                if key not in ("episodes", "quality")
            }
            for run_id in run_ids
        ]
        _write_json(output_dir / "data" / "runs.json", {"runs": summaries})

        media_root = output_dir / "media"
        media_root.mkdir(parents=True, exist_ok=True)
        media_target = media_root / media_name
        if not media_target.exists():
            media_target.write_bytes(video_bytes)
        elif media_target.read_bytes() != video_bytes:
            raise ValueError("content-addressed media path has conflicting bytes")
        if walkthrough_bytes is not None and walkthrough_name is not None:
            walkthrough_target = media_root / walkthrough_name
            if not walkthrough_target.exists():
                walkthrough_target.write_bytes(walkthrough_bytes)
            elif walkthrough_target.read_bytes() != walkthrough_bytes:
                raise ValueError("content-addressed walkthrough path has conflicting bytes")

        for run_id in run_ids:
            run_dir = source_root / run_id
            detail = details[run_id]
            _write_json(output_dir / "data" / "runs" / f"{run_id}.json", detail)
            for episode in detail["episodes"]:
                episode_id = episode["episode_id"]
                trace = store.trace(run_id, episode_id)
                _write_json(
                    output_dir / "data" / "runs" / run_id / "episodes" / episode_id / "trace.json",
                    trace,
                )
                steps = trace["steps"]
                trace_start = steps[0]["timestamp_s"] if steps else 0.0
                # RunStore reads sidecars under media/<episode>/; place the asset
                # there too, then use its validated normalized result.
                episode_asset = run_dir / "media" / episode_id / "synthetic.mp4"
                episode_asset.parent.mkdir(parents=True, exist_ok=True)
                episode_asset.write_bytes(video_bytes)
                _write_json(
                    run_dir / "media" / episode_id / "media.json",
                    {
                        "schema_version": 1,
                        "episode_id": episode_id,
                        "streams": [
                            {
                                "camera": "synthetic.showcase",
                                "path": f"media/{episode_id}/synthetic.mp4",
                                "mime_type": "video/mp4",
                                "duration_s": 3.0,
                                "trace_start_s": trace_start,
                            }
                        ],
                        "events": [],
                    },
                )
                validated = store.media_manifest(run_id, episode_id)
                validated["streams"][0]["path"] = f"/media/{media_name}"
                validated["streams"][0]["url"] = f"/media/{media_name}"
                _write_json(
                    output_dir / "data" / "runs" / run_id / "episodes" / episode_id / "media.json",
                    validated,
                )

        _write_json(
            output_dir / "data" / "runs" / CANDIDATE_ID / "compare" / f"{BASELINE_ID}.json",
            store.compare(CANDIDATE_ID, BASELINE_ID),
        )
        _write_json(
            output_dir
            / "data"
            / "runs"
            / CANDIDATE_ID
            / "compare"
            / f"{BASELINE_ID}.acknowledged.json",
            store.compare(CANDIDATE_ID, BASELINE_ID, acknowledge_incompatible=True),
        )

    manifest = {
        "schema_version": 1,
        "source_commit": source_commit,
        "source_repository": SOURCE_REPOSITORY,
        "candidate_id": CANDIDATE_ID,
        "baseline_id": BASELINE_ID,
        "evidence_kind": "synthetic",
        "limitations": LIMITATIONS,
        "walkthrough_video_url": (
            f"/media/{walkthrough_name}" if walkthrough_name is not None else None
        ),
        "assets": {
            f"/media/{media_name}": media_hash,
            **(
                {f"/media/{walkthrough_name}": walkthrough_hash}
                if walkthrough_name is not None and walkthrough_hash is not None
                else {}
            ),
        },
        "inventory": {
            f"/{path.relative_to(output_dir).as_posix()}": hashlib.sha256(
                path.read_bytes()
            ).hexdigest()
            for path in sorted(output_dir.rglob("*"))
            if path.is_file() and path.name != "showcase.json"
        },
    }
    _write_json(output_dir / "showcase.json", manifest)
    return manifest
